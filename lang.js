function getLang() {
  try {
    return localStorage.getItem("urpaq_lang") || "ru";
  } catch (error) {
    return "ru";
  }
}

function tr(key) {
  const lang = getLang();
  const entry = TRANSLATIONS[key];
  if (!entry) return key;
  return entry[lang] || entry.ru || key;
}

function modalText(action, field) {
  const lang = getLang();
  const entry = MODAL_COPY[action] && MODAL_COPY[action][field];
  if (!entry) return "";
  return entry[lang] || entry.ru || "";
}

function setLang(lang) {
  try {
    localStorage.setItem("urpaq_lang", lang);
  } catch (error) {}
  applyTranslations();
}

function applyTranslations() {
  document.documentElement.lang = getLang();
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = tr(node.dataset.i18n);
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === getLang());
  });
}

function renderLangSwitch() {
  document.querySelectorAll(".lang-switch").forEach((container) => {
    container.innerHTML = "";
    [
      ["ru", "RU"],
      ["kk", "KZ"],
      ["en", "EN"]
    ].forEach(([lang, label]) => {
      const button = document.createElement("button");
      button.className = "lang-btn";
      button.type = "button";
      button.dataset.lang = lang;
      button.textContent = label;
      button.addEventListener("click", () => setLang(lang));
      container.appendChild(button);
    });
  });
}

function initMenus() {
  const toggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector(".nav-links");
  const actions = document.querySelector(".header-actions");
  if (toggle && nav && actions) {
    toggle.addEventListener("click", () => {
      const isOpen = toggle.classList.toggle("is-open");
      nav.classList.toggle("is-open", isOpen);
      actions.classList.toggle("is-open", isOpen);
      toggle.setAttribute("aria-expanded", String(isOpen));
    });
  }

  const contact = document.querySelector(".contact-dropdown");
  const contactToggle = document.querySelector(".contact-toggle");
  if (contact && contactToggle) {
    contactToggle.addEventListener("click", (event) => {
      event.stopPropagation();
      const isOpen = contact.classList.toggle("is-open");
      contactToggle.setAttribute("aria-expanded", String(isOpen));
    });
    document.addEventListener("click", (event) => {
      if (!contact.contains(event.target)) {
        contact.classList.remove("is-open");
        contactToggle.setAttribute("aria-expanded", "false");
      }
    });
  }
}

function initModal() {
  const modal = document.getElementById("modal");
  if (!modal) return;
  const title = document.getElementById("modal-title");
  const text = document.getElementById("modal-text");
  const amount = modal.querySelector(".amount-field");
  const form = document.getElementById("action-form");

  function open(action) {
    title.textContent = modalText(action, "title");
    text.textContent = modalText(action, "text");
    if (amount) amount.hidden = !MODAL_COPY[action]?.amount;
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("is-locked");
    const firstInput = modal.querySelector("input");
    if (firstInput) firstInput.focus();
  }

  function close() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("is-locked");
  }

  document.querySelectorAll("[data-open-modal]").forEach((node) => {
    node.addEventListener("click", () => open(node.dataset.openModal));
  });
  modal.querySelectorAll("[data-close-modal]").forEach((node) => node.addEventListener("click", close));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") close();
  });
  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      form.reset();
      close();
      alert(getLang() === "en" ? "Request sent. We will contact you soon." : getLang() === "kk" ? "Өтінім жіберілді. Жақында хабарласамыз." : "Заявка отправлена. Мы скоро свяжемся с вами.");
    });
  }
}

document.addEventListener("DOMContentLoaded", () => {
  renderLangSwitch();
  applyTranslations();
  initMenus();
  initModal();
});
